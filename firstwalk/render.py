def outputs(walk):
    return {MD_NAME: render_md(walk).rstrip("\n") + "\n", HTML_NAME: render_html(walk)}


def check(walk, out_dir=OUT_DIR):
    """The names of generated files that are missing or differ from the data."""
    bad = []
    for name, want in outputs(walk).items():
        try:
            with open(os.path.join(out_dir, name), "rb") as f:
                have = f.read().decode("utf-8").replace("\r\n", "\n")
        except OSError:
            bad.append(name)
            continue
        if have != want:
            bad.append(name)
    return bad


def write(walk, out_dir=OUT_DIR):
    os.makedirs(out_dir, exist_ok=True)
    for name, text in outputs(walk).items():
        with open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Render firstwalk/walk.json into the checklist pages.")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true", help="write docs/firstwalk/CHECKLIST.md and checklist.html")
    g.add_argument("--check", action="store_true", help="exit 1 if a committed page differs from the data")
    ap.add_argument("--walk", default=WALK)
    ap.add_argument("--out-dir", default=OUT_DIR)
    a = ap.parse_args(argv)
    walk = load_walk(a.walk)
    if a.write:
        write(walk, a.out_dir)
        print("wrote %s and %s in %s" % (MD_NAME, HTML_NAME, a.out_dir))
        return 0
    bad = check(walk, a.out_dir)
    if bad:
        print("DRIFT: %s differ from firstwalk/walk.json. Run: python firstwalk/render.py --write" % ", ".join(bad))
        return 1
    print("checklist pages match walk.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
