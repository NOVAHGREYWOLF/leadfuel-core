r"""SURFACE firstwalk: render `walk.json` into the owner's checklist.

    python firstwalk/render.py --write     # write docs/firstwalk/CHECKLIST.md and checklist.html
    python firstwalk/render.py --check     # exit 1 if either committed file differs from the data

`walk.json` is the only source. Both outputs are generated: edit the data, never the pages. The
check mode is how a test (and a human) notices that somebody did.

What the HTML page is: one self-contained file (no network, no script or style from anywhere else).
Per step there is a radio (not tested, pass, fail, closed by design) and one proof field. The marks
are kept in this browser's localStorage when it works (every access is in try/catch, and the page is
fully usable without it) and leave as one file through the export button:

    {"schema": "firstwalk.marks/1", "exported_at": "...Z",
     "marks": {"<step id>": {"state": "pass|fail|closed_by_design|not_tested", "proof": "...", "at": "...Z"}},
     "cells": {"<cell id>": {"note": "..."}}}

`firstwalk/smoke.py run --marks FILE` is the only reader. A step the owner did not mark is
not tested, never a pass.

Stdlib only. Nothing here reads the network, the hub or any secret.
"""
