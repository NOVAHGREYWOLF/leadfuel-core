def load_walk(path=WALK):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def cells(walk):
    """Lines then rooms, in walk order: (kind, cell)."""
    return [("line", c) for c in walk["lines"]] + [("room", c) for c in walk["rooms"]]


def step_ids(walk):
    return [s["id"] for _, c in cells(walk) for s in c["steps"]]


# ----------------------------------------------------------------------------- markdown

def _md(text):
    """One table cell: no newline, pipes escaped."""
    return str(text).replace("\r", " ").replace("\n", " ").replace("|", "\\|")


def _queue_text(items):
    return ", ".join("`%s`" % i for i in items) if items else "none"


def render_md(walk):
    mock = {m["id"]: m for m in walk["mockups"]}
    o = []
    w = o.append
    w("# NovahOS first walk: the owner's checklist")
    w("")
