    w('<section class="cell" id="cell-%s" data-cell="%s">' % (_h(c["id"]), _h(c["id"])))
    w('<header><h3>%s: %s</h3><span class="badge b-not_tested">not tested</span></header>' % (_h(c["id"]), _h(c["title"])))
    if kind == "line":
        w("<p><strong>You do:</strong> %s</p>" % _h(c["you_do"]))
    else:
        w("<p><strong>Where:</strong> %s</p>" % _h(c["where"]))
    meta = []
    if c.get("mockups"):
        meta.append("Mockups: " + ", ".join(
            '<a href="#mock-%s">%s %s</a>' % (_h(i), _h(i), _h(mock[i]["title"])) for i in c["mockups"]))
    meta.append("Queue items: " + (", ".join("<code>%s</code>" % _h(q) for q in c.get("queue", [])) or "none"))
